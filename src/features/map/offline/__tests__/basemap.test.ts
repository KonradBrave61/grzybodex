// code-guard: intentional-duplicate - test names (layers, style) fuzzy-match production identifiers; no logic is duplicated.
import layers from '../basemap-layers.json';

// basemap.ts require()s binary map assets for Metro; Jest cannot parse them, so they become asset ids here.
jest.mock('@/../assets/maps/overview-z9.pmtiles', () => 1);
for (const font of ['regular', 'medium', 'italic']) {
  for (const range of ['0-255', '256-511', '1024-1279', '8192-8447']) jest.mock(`@/../assets/maps/noto-${font}-${range}.pbf`, () => 1);
}
// eslint-disable-next-line @typescript-eslint/no-require-imports -- must load after the asset mocks above
const { buildStyle } = require('../basemap') as typeof import('../basemap');

const OPTS = { mode: 'detail' as const, overviewUrl: 'pmtiles://file:///o.pmtiles', glyphsUrl: 'file:///g/{fontstack}/{range}.pbf', packUrls: ['pmtiles://file:///p.pmtiles'] };
const text = (style: ReturnType<typeof buildStyle>) => JSON.stringify(style.layers);

describe('buildStyle labels', () => {
  it('reads Polish names by default (as generated by @protomaps/basemaps lang pl)', () => {
    const pl = buildStyle(OPTS);
    expect(text(pl)).toContain('"name:pl"');
    expect(text(buildStyle({ ...OPTS, lang: 'pl' }))).toBe(text(pl));
    expect(pl.layers).toHaveLength(layers.length + 1 + layers.filter((l) => 'source' in l).length);
  });

  it('reads English names for English, with the same fallbacks to the local name', () => {
    const en = buildStyle({ ...OPTS, lang: 'en' });
    const pl = buildStyle(OPTS);
    expect(text(en)).not.toContain('name:pl');
    expect(text(en)).toContain('["coalesce",["get","name:en"],["get","pgf:name"],["get","name"]]');
    expect(text(en)).toBe(text(pl).split('"name:pl"').join('"name:en"'));
    expect(en.layers.map((l) => l.id)).toEqual(pl.layers.map((l) => l.id));
  });
});
