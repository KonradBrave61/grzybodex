// code-guard: intentional-duplicate - short style names (layers, sources, source) fuzzy-match other modules; no logic is duplicated.
import { Asset } from 'expo-asset';
import { Directory, File, Paths } from 'expo-file-system';

import type { Lang } from '@/i18n/i18n';

import layers from './basemap-layers.json';

/**
 * MapLibre style of the notebook map. Data: Protomaps basemap (OpenStreetMap, ODbL), flavor "light", Polish or English labels,
 * font Noto Sans (OFL). Icons/sprites are left out (no sprite sheet offline); labels use glyphs copied to the phone.
 *
 *  - "overview" (Ogólna): only the built-in map of Poland (zoom 0–9, stretched beyond) — never touches the network.
 *  - "detail" (Szczegóły): built-in map, then OpenTopoMap raster where there is network, then downloaded
 *    voivodeship packs on top (they win wherever they exist). Offline, missing raster tiles stay transparent.
 */
export type MapMode = 'overview' | 'detail';

type StyleLayer = { id: string; type: string; source?: string; [k: string]: unknown };
const BASE = layers as StyleLayer[];

export const OTM_TILES = 'https://tile.opentopomap.org/{z}/{x}/{y}.png';

/**
 * basemap-layers.json was generated by @protomaps/basemaps with lang 'pl'. For English the label expressions read
 * `name:en` instead of `name:pl` (same fallbacks to the local `name`). Checked against @protomaps/basemaps 5.7.2:
 * its lang 'pl' output equals this file and its lang 'en' output equals this swap (all text-field expressions).
 */
let englishLayers: StyleLayer[] | null = null;
function layersFor(lang: Lang): StyleLayer[] {
  if (lang === 'pl') return BASE;
  englishLayers ??= JSON.parse(JSON.stringify(BASE).split('"name:pl"').join('"name:en"')) as StyleLayer[];
  return englishLayers;
}

/**
 * RESPONSIBILITY: Składa styl MapLibre dla trybu Ogólna/Szczegóły z wbudowanej mapy, pobranych paczek i (online) OpenTopoMap
 * INPUTS:         mode; lang: język podpisów mapy (domyślnie 'pl'); overviewUrl / packUrls: adresy pmtiles://file://… (trusted — pliki aplikacji); glyphsUrl: szablon file://…/{fontstack}/{range}.pbf
 * OUTPUTS:        obiekt stylu (version 8): źródła + warstwy w kolejności rysowania
 * AUTHN:          none
 * AUTHZ:          none
 * TOUCHES:        none (czysta funkcja; sieć dotyka dopiero MapLibre — tylko kafelki OTM w trybie „detail”)
 * ERRORS:         none
 */
export function buildStyle(opts: { mode: MapMode; lang?: Lang; overviewUrl: string; glyphsUrl: string; packUrls: readonly string[] }) {
  const base = layersFor(opts.lang ?? 'pl');
  const sources: Record<string, object> = { overview: { type: 'vector', url: opts.overviewUrl } };
  const all: StyleLayer[] = base.map((l) => ({ ...l, id: `o-${l.id}`, ...(l.source ? { source: 'overview' } : {}) }));
  if (opts.mode === 'detail') {
    sources.otm = { type: 'raster', tiles: [OTM_TILES], tileSize: 256, maxzoom: 17 };
    all.push({ id: 'otm', type: 'raster', source: 'otm' });
    opts.packUrls.forEach((url, i) => {
      sources[`pack${i}`] = { type: 'vector', url };
      for (const l of base) if (l.source) all.push({ ...l, id: `p${i}-${l.id}`, source: `pack${i}` });
    });
  }
  return { version: 8 as const, glyphs: opts.glyphsUrl, sources, layers: all };
}

